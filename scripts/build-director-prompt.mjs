// Compiles the script director's rules from the skill files into the backend, so the one-call
// planner and the skills can never drift apart (docs/PRODUCT_FLOW_V2.md → Where the skills live).
// Run after editing any of the source files: `npm run director:prompt`.
import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const sources = {
  SCRIPT_FOR_MOTION: ".claude/skills/gm-skill-authoring/references/script-for-motion.md",
  WATCHABILITY: ".claude/skills/gm-skill-authoring/references/watchability.md",
  ROUTING: ".claude/skills/gm-script-director/references/routing.md",
  MOTION_DIRECTION: ".claude/skills/gm-script-director/references/motion-direction.md",
  SHOT_DIRECTION: ".claude/skills/gm-script-director/references/shot-direction.md"
};

let out = "// GENERATED by scripts/build-director-prompt.mjs from the gm-* skill files. Do not edit by hand.\n";
for (const [name, path] of Object.entries(sources)) {
  const text = await readFile(resolve(root, path), "utf8");
  out += `\n/** Source: ${path} */\nexport const ${name} = ${JSON.stringify(text)};\n`;
}
const target = resolve(root, "backend/src/plan/director-prompt.generated.ts");
await writeFile(target, out);
console.log(`wrote ${target}`);
